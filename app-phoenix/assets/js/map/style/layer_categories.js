export function enabledPoiKinds(disabledGroups) {
  const disabled = new Set(disabledGroups || [])
  const kinds = []
  for (const [key, group] of Object.entries(POI_GROUPS)) {
    if (!disabled.has(key)) {
      kinds.push(...group.kinds)
    }
  }
  return kinds
}


