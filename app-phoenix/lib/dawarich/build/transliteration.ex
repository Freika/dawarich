  def export(root) do
    tree = Dawarich.Build.I18n.tree(root)

    rules =
      for locale <- Dawarich.Build.I18n.locales(),
          rule = rule(tree, locale),
          rule.values != [],
          do:
            {locale,
             %OrderedObject{values: Enum.map(rule.values, fn {k, v} -> {k, to_string(v)} end)}}

    %OrderedObject{
      values: [
        {"default", %OrderedObject{values: @default}},
        {"rules", %OrderedObject{values: rules}}
      ]
    }
  end

  defp rule(tree, locale) do
    value =
      case dig(tree, [locale, "i18n", "transliterate", "rule"]) do
        nil -> dig(tree, ["en", "i18n", "transliterate", "rule"]) || %OrderedObject{values: []}
        value -> value
      end

    case value do
      %OrderedObject{} -> value
      _ -> raise ArgumentError, "#{locale}: only hash transliteration rules can be exported"
    end
  end

  defp dig(value, []), do: value
  defp dig(%OrderedObject{} = object, [key | rest]), do: dig(object[key], rest)
  defp dig(_, _), do: nil
end
